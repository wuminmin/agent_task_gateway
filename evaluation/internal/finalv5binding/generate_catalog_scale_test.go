//go:build taskgate_scale

// This case rebuilds the complete binding from a freshly generated Catalog.
// It carries a multi-minute budget and never finished inside the acceptance
// run's per-package limit, so it belongs on the taskgate_scale lane the
// repository already reserves for costly scale work.

package finalv5binding_test

import (
	"os"
	"path"
	"path/filepath"
	"reflect"
	"strings"
	"testing"

	"taskbound.local/agent-data-gateway/evaluation/finalv5contracts"
	"taskbound.local/agent-data-gateway/evaluation/finalv5oracle"
	"taskbound.local/agent-data-gateway/evaluation/internal/finalv5binding"
	"taskbound.local/agent-data-gateway/evaluation/internal/finalv5publication"
	"taskbound.local/agent-data-gateway/internal/catalog"
)

func TestBuildCompleteBindingRequiresCompleteGeneratedCatalog(t *testing.T) {
	repositoryRoot := bindingRepositoryRoot(t)
	baseBytes, err := os.ReadFile(filepath.Join(repositoryRoot, "config", "catalog.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	base, err := catalog.Parse(baseBytes)
	if err != nil {
		t.Fatal(err)
	}
	scaleBytes, err := os.ReadFile(filepath.Join(repositoryRoot, filepath.FromSlash(path.Join(
		path.Dir(finalv5publication.C2CandidateRelativePath), "catalog.yaml"))))
	if err != nil {
		t.Fatal(err)
	}
	candidate, err := finalv5publication.BuildCatalogCandidate(baseBytes, scaleBytes, base.Sources[0].SchemaDigest)
	if err != nil {
		t.Fatal(err)
	}
	candidateCatalog, err := candidate.Catalog()
	if err != nil {
		t.Fatal(err)
	}
	contractRuntime, err := finalv5contracts.LoadRuntime()
	if err != nil {
		t.Fatal(err)
	}
	dataset, err := contractRuntime.DatasetIdentitySHA256()
	if err != nil {
		t.Fatal(err)
	}
	oracleOptions := finalv5oracle.StreamSetOptions{TempDir: t.TempDir(), MaxInMemoryMembers: 2_100_000}
	scaleOutcomes, err := finalv5binding.GenerateScaleOutcomeCandidateExpectations(candidateCatalog.SHA256,
		oracleOptions)
	if err != nil {
		t.Fatal(err)
	}
	input := finalv5binding.CompleteBindingInput{
		DatasetSHA256: dataset, DatasetProbeSHA256: observedProbeSHA256, Catalog: candidateCatalog,
		ScaleOutcomes: scaleOutcomes, ArtifactRuntime: contractRuntime,
		ScaleManifests:   externalTrackedScaleManifests(t),
		ProvSQLManifests: externalTrackedProvSQLManifests(t),
		OracleOptions:    oracleOptions,
	}
	binding, value, err := finalv5binding.BuildCompleteBinding(input)
	if err != nil {
		t.Fatal(err)
	}
	if binding.CatalogSHA256 != candidate.SHA256() || len(binding.Section.Scale.DependencyE2E) != 12 ||
		len(binding.Section.Artifact.ResultHeavy) != 6 || len(binding.Section.ProvSQL.TaskGate) != 105 {
		t.Fatalf("generated Catalog/closure = %s/%d/%d/%d, want %s/12/6/105", binding.CatalogSHA256,
			len(binding.Section.Scale.DependencyE2E), len(binding.Section.Artifact.ResultHeavy),
			len(binding.Section.ProvSQL.TaskGate), candidate.SHA256())
	}
	if !binding.Section.Scale.EnableExtreme || !strings.Contains(string(value), `"enable_extreme":true`) {
		t.Fatal("generated binding omitted the source-controlled Scale extreme feature flag")
	}
	if binding.FileSHA256 != externalSHA256(value) || !strings.HasSuffix(string(value), "\n") {
		t.Fatal("generated bytes are not the exact canonical file identity")
	}
	reparsed, err := finalv5binding.Parse(value)
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(binding, reparsed) {
		t.Fatal("generated binding differs after strict parse")
	}
	if err := finalv5binding.ValidateAgainstCatalog(binding, candidateCatalog); err != nil {
		t.Fatalf("complete generated Catalog was rejected: %v", err)
	}
	if err := finalv5binding.ValidateAgainstCatalog(binding, base); err == nil {
		t.Fatal("incompatible base Catalog without approved Scale material was accepted")
	}
	outcomeByCandidateFacts := make(map[int64]string, 3)
	candidateFactsByOutcome := make(map[string]int64, 3)
	for scale, cell := range binding.Section.Scale.DependencyE2E {
		if err := finalv5binding.ValidateBoundOutcomeCandidate(cell.OutcomeCandidate); err != nil {
			t.Fatalf("generated Scale cell %s has no strict five-member Outcome candidate: %v", scale, err)
		}
		identity := cell.OutcomeCandidate.OrdinarySetSHA256 + strings.Join(cell.OutcomeCandidate.Members, "")
		if prior, present := outcomeByCandidateFacts[cell.Candidate.DependencyFacts]; present && prior != identity {
			t.Fatalf("Scale cells with %d candidate Facts disagree on their strict Outcome members",
				cell.Candidate.DependencyFacts)
		}
		if priorFacts, present := candidateFactsByOutcome[identity]; present &&
			priorFacts != cell.Candidate.DependencyFacts {
			t.Fatalf("Scale candidate sizes %d and %d unexpectedly share one strict Outcome identity",
				priorFacts, cell.Candidate.DependencyFacts)
		}
		outcomeByCandidateFacts[cell.Candidate.DependencyFacts] = identity
		candidateFactsByOutcome[identity] = cell.Candidate.DependencyFacts
	}
	if len(outcomeByCandidateFacts) != 3 || len(candidateFactsByOutcome) != 3 {
		t.Fatalf("generated strict Outcome closure has %d candidate sizes and %d identities; want 3/3",
			len(outcomeByCandidateFacts), len(candidateFactsByOutcome))
	}
}
